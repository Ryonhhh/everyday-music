_PREFIX = re.compile(r'^[A-Za-z0-9_.-]{1,24}\+')
_cache = {}
_KEYS_BY_LEN = sorted(FONT_MAPS, key=len, reverse=True)


def _strip_prefix(name):
    """去掉 ``DY11+`` / ``DLF-0-280-123456+`` 这类子集前缀。"""
    m = _PREFIX.match(name)
    return name[m.end():] if m else name


def font_map_for(font_name):
    """返回该字体名对应的映射 dict，找不到返回 None。"""
    if not font_name:
        return None
    if font_name in _cache:
        return _cache[font_name]
    found = None
    if font_name in FONT_MAPS:
        found = FONT_MAPS[font_name]
    else:
        stripped = _strip_prefix(font_name)
        if stripped in FONT_MAPS:
            found = FONT_MAPS[stripped]
        else:
            # 有些字体名前面还挂了一段 DLF-...- 的前缀，用子串再试一次；
            # 按长度从长到短匹配，且要求匹配后面不是数字，避免 ZFRGvT-4 误中 ZFRGvT-44。
            for key in _KEYS_BY_LEN:
                idx = font_name.find(key)
                if idx < 0:
                    continue
                tail = font_name[idx + len(key):]
                if tail and tail[0].isdigit():
                    continue
                found = FONT_MAPS[key]
                break
    _cache[font_name] = found
    return found


def fix_text(text, font_name):
    """按字体名把一段文本里的码位字符换成真实字符；没有该字体映射则原样返回。"""
    if not text:
        return text
    fmap = font_map_for(font_name)
    if not fmap:
        return text
    return ''.join(fmap.get(ch, ch) for ch in text)


def build_page_text(page):
    """传入 pymupdf.Page，返回修正后的纯文本（数字/字母已还原）。"""
    raw = page.get_text('rawdict')
    lines = []
    for block in raw.get('blocks', []):
        if block.get('type') != 0:
            continue                      # 图片等非文本块
        for line in block.get('lines', []):
            chunks = []
            for span in line.get('spans', []):
                chars = span.get('chars')
                if not chars:
                    continue              # 没有 chars 的 span 直接跳过
                chunks.append(fix_text(''.join(c.get('c', '') for c in chars),
                                       span.get('font') or ''))
            if chunks:
                lines.append(''.join(chunks))
    return '\n'.join(lines)
